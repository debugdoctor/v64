        name: insn + ": sets CF and clears OF/SF/ZF/AF/PF",
        code,
        set: { [reg]: 0x0123456789ABCDEFn },
        // The destination's new value is random, so it is not checked; it is
        // named here so the "no other register moved" check below skips it.
