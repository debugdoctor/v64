#!/usr/bin/env node

// BMI1/BMI2/ADX and random-instruction flag tests for both 64-bit engines.
//
// Harness rules:
//   * Encodings come from a clang assemble/objdump round trip, never from
//     hand-written VEX bytes or from reading the VEX fields by eye. Operand
//     roles are read off that disassembly, which prints sources first.
//   * The harness verifies its own register read-back before trusting results.
//   * Memory-operand forms get their own cases; the register form exercises a
//     different decode path and would not notice a broken memory read.
//
// Requires a debug wasm build: `make build/v64-debug.wasm`
// Run with: `node tests/jit64/bmi1.js`
//
// Encodings, from:
//   clang -target x86_64-unknown-linux-gnu -march=haswell -c  &&  objdump -d
//     andnq  %rax, %rbx, %rcx   c4 e2 e0 f2 c8
//     andnq  (%r15), %rbx, %rcx c4 c2 e0 f2 0f
//     bextrq %rax, %rbx, %rcx   c4 e2 f8 f7 cb
//     blsiq  %rax, %rbx         c4 e2 e0 f3 d8
//     blsmskq %rax, %rbx        c4 e2 e0 f3 d0
//     blsrq  %rax, %rbx         c4 e2 e0 f3 c8
//     mulxq  %rax, %rbx, %rcx   c4 e2 e3 f6 c8
//     sarxq  %rax, %rbx, %rcx   c4 e2 fa f7 cb
//     rorxq  $0x5, %rax, %rbx   c4 e3 fb f0 d8 05
//     rorxl  $0x5, %eax, %ebx   c4 e3 7b f0 d8 05
//     adcxq  %rax, %rcx         66 48 0f 38 f6 c8
//     adoxq  %rax, %rcx         f3 48 0f 38 f6 c8
//     adcx   %eax, %ecx         66 0f 38 f6 c8
//     mulxq  (%r15), %rbx, %rcx c4 c2 e3 f6 0f
//
// Operand roles, read off that disassembly (AT&T prints sources first):
//   andnq  %rax, %rbx, %rcx -> dst=rcx (ModRM.reg), src1=rbx (VEX.vvvv),
//                                src2=rax (rm)
//   bextrq %rax, %rbx, %rcx -> dst=rcx, ctrl=rax (VEX.vvvv), src=rbx (rm)
//   blsiq  %rax, %rbx       -> dst=rbx (VEX.vvvv), src=rax (rm)
//   mulxq  %rax, %rbx, %rcx -> hi=rcx (ModRM.reg), lo=rbx (VEX.vvvv),
//                                and the multiplier is rax (rm)
//   sarxq  %rax, %rbx, %rcx -> dst=rcx, src=rbx (rm), count=rax (VEX.vvvv)
//   rorxq  $n, %rax, %rbx   -> dst=rbx (ModRM.reg), src=rax (rm)
//   adcxq  %rax, %rcx       -> dst=rcx (ModRM.reg), src=rax (rm)
//   mulxq  (%r15), %rbx, %rcx -> multiplier=[r15] (rm), multiplicand=rdx (implicit)
//
// RDRAND / RDSEED, from `clang -target x86_64-unknown-linux-gnu -c && objdump -d`:
//   rdrandq %rax   48 0f c7 f0      rdseedq %rbx   48 0f c7 fb
//   rdrandl %eax   0f c7 f0         rdseedl %ebx   0f c7 fb
//   rdrandw %ax    66 0f c7 f0      rdseedw %bx    66 0f c7 fb
//   rdseedq %r12   49 0f c7 fc      rdrandq %r13   49 0f c7 f5
//
// BMI1 instructions require VEX; the corresponding legacy slots raise #UD.
//
// The counts above are the ones the cases with a distinctive value use. The
// rest differ only in the immediate, and are listed here as generated by
// objdump so that tests/vex-encoding-check.py covers every hand-written byte
// string in this file: an encoding absent from the tables is one nobody has
// vouched for.
//   rorxq 0x0,rax,rbx    c4 e3 fb f0 d8 00
//   rorxq 0x3f,rax,rbx    c4 e3 fb f0 d8 3f
//   rorxq 0x20,rax,rbx    c4 e3 fb f0 d8 20
//   rorxl 0x0,eax,ebx    c4 e3 7b f0 d8 00
//   rorxl 0x1f,eax,ebx    c4 e3 7b f0 d8 1f
//   rorxl 0x21,eax,ebx    c4 e3 7b f0 d8 21
import { v64 } from "../../src/main.js";
